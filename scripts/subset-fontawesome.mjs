#!/usr/bin/env node
/**
 * 生成 Font Awesome 子集（仅包含 static/ 中实际引用的图标），输出到
 * static/vendor/fontawesome@<version>/ 。
 *
 * 旧标记 `<i class="fas fa-xxx">` 保持不变；只是 CSS 与字体被裁剪。
 * 新增/删除图标后需重新运行：npm run vendor:fa
 * 约定：图标类名必须以完整字面量 `fa-xxx` 出现在源码中（动态拼接无法被扫描）。
 *
 * 依赖（devDependencies）：@fortawesome/fontawesome-free、subset-font
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FA = path.join(ROOT, 'node_modules', '@fortawesome', 'fontawesome-free');
const STATIC = path.join(ROOT, 'static');
const SCAN_EXT = new Set(['.html', '.js', '.mjs', '.css']);
const SKIP_DIRS = new Set(['vendor', 'node_modules']);

function walk(dir, out = []) {
    for (const name of readdirSync(dir)) {
        const full = path.join(dir, name);
        if (statSync(full).isDirectory()) {
            if (!SKIP_DIRS.has(name)) walk(full, out);
        } else if (SCAN_EXT.has(path.extname(name))) {
            out.push(full);
        }
    }
    return out;
}

/** 扫描 static/（不含 vendor）中出现的 fa-xxx 字面量；插件目录里的页面也在 static/ 下 */
export function collectUsedFaTokens(extraDirs = []) {
    const tokens = new Set();
    const dirs = [STATIC, ...extraDirs];
    for (const dir of dirs) {
        for (const file of walk(dir)) {
            const text = readFileSync(file, 'utf8');
            for (const m of text.matchAll(/(?<![\w-])fa-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) tokens.add(m[1]);
        }
    }
    return tokens;
}

/** 将压缩 CSS 按顶层规则拆分（处理 @font-face / @media 嵌套） */
function splitTopLevelRules(css) {
    const rules = [];
    let depth = 0;
    let start = 0;
    for (let i = 0; i < css.length; i++) {
        const c = css[i];
        if (c === '{') depth++;
        else if (c === '}') {
            depth--;
            if (depth === 0) {
                rules.push(css.slice(start, i + 1));
                start = i + 1;
            }
        }
    }
    return rules;
}

const GLYPH_RULE = /^\s*((?:\.fa-[a-z0-9-]+,?)+)\{--fa:"\\([0-9a-fA-F]+)"\}\s*$/;

export async function buildSubset({ extraDirs = [] } = {}) {
    const version = JSON.parse(readFileSync(path.join(FA, 'package.json'), 'utf8')).version;
    const used = collectUsedFaTokens(extraDirs);
    const css = readFileSync(path.join(FA, 'css', 'all.min.css'), 'utf8').replace(/^\/\*![\s\S]*?\*\//, '');
    const kept = [];
    const codepoints = new Set();
    const resolved = new Set();

    for (const rule of splitTopLevelRules(css)) {
        const glyph = GLYPH_RULE.exec(rule);
        if (glyph) {
            const names = glyph[1].split(',').map(s => s.replace(/^\.fa-/, '')).filter(Boolean);
            const hit = names.filter(n => used.has(n));
            if (hit.length) {
                hit.forEach(n => resolved.add(n));
                kept.push(`${hit.map(n => `.fa-${n}`).join(',')}{--fa:"\\${glyph[2]}"}`);
                codepoints.add(parseInt(glyph[2], 16));
            }
            continue;
        }
        if (rule.startsWith('@font-face')) {
            // 只保留 Solid(900) 与 Brands，且改写为子集 woff2（去掉 ttf 回退）
            if (rule.includes('Font Awesome 6 Brands')) {
                kept.push('@font-face{font-family:"Font Awesome 6 Brands";font-style:normal;font-weight:400;font-display:block;src:url(fa-brands-subset.woff2) format("woff2")}');
            } else if (rule.includes('font-weight:900')) {
                kept.push('@font-face{font-family:"Font Awesome 6 Free";font-style:normal;font-weight:900;font-display:block;src:url(fa-solid-subset.woff2) format("woff2")}');
            }
            continue;
        }
        // 其它基础/工具类规则（fa-spin、fa-fw、fa-2x、动画关键帧 …）原样保留
        kept.push(rule.trim());
    }

    const unresolved = [...used].filter(n => !resolved.has(n) && !css.includes(`.fa-${n}`));
    const text = String.fromCodePoint(...[...codepoints].sort((a, b) => a - b));
    const outDir = path.join(STATIC, 'vendor', `fontawesome@${version}`);
    mkdirSync(outDir, { recursive: true });
    const header = `/*! Font Awesome Free ${version} subset (${resolved.size} icons) - https://fontawesome.com | Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT. Generated by scripts/subset-fontawesome.mjs */\n`;
    writeFileSync(path.join(outDir, 'fa-subset.css'), header + kept.join('\n') + '\n');
    for (const [name, src] of [['fa-solid-subset.woff2', 'fa-solid-900.woff2'], ['fa-brands-subset.woff2', 'fa-brands-400.woff2']]) {
        const buf = await subsetFont(readFileSync(path.join(FA, 'webfonts', src)), text, { targetFormat: 'woff2' });
        writeFileSync(path.join(outDir, name), buf);
    }
    return { version, icons: resolved.size, unresolved, outDir };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const result = await buildSubset();
    console.log(`Font Awesome ${result.version}: ${result.icons} icons -> ${path.relative(ROOT, result.outDir)}`);
    if (result.unresolved.length) {
        console.log(`(non-glyph fa-* tokens ignored: ${result.unresolved.join(', ')})`);
    }
}
